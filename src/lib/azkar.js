const RECENT_KEY = 'flowboard.azkarRecent';
const MIN_GAP = 4 * 60_000;
const MAX_GAP = 12 * 60_000;

/** Random zikr, never one of the last 10 shown. */
export function nextZikr() {
  let recent = [];
  try {
    recent = JSON.parse(localStorage.getItem(RECENT_KEY) || '[]');
  } catch {}
  const pool = AZKAR.map((_, i) => i).filter((i) => !recent.includes(i));
  const pick = pool[Math.floor(Math.random() * pool.length)];
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify([...recent, pick].slice(-10)));
  } catch {}
  return AZKAR[pick];
}

/** While enabled, shows a zikr at random intervals (first one shortly after opening). */
export function useAzkar() {
  const on = useStore((s) => s.azkarOn);
  useEffect(() => {
    if (!on) return;
    let timer;
    const schedule = (delay) => {
      timer = setTimeout(() => {
        useStore.getState().toast(nextZikr(), { tone: 'zikr', duration: 14_000 });
        schedule(MIN_GAP + Math.random() * (MAX_GAP - MIN_GAP));
      }, delay);
    };
    schedule(20_000 + Math.random() * 40_000);
    return () => clearTimeout(timer);
  }, [on]);
}
